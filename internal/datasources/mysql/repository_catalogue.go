func (c *catalogueReader) pieceCredits(rows []queries.ListPublicPieceCreditsRow) []domain.PieceCredit {
	credits := make([]domain.PieceCredit, 0, len(rows))
	for _, row := range rows {
		credit := domain.PieceCredit{
			Role:        enumOf[domain.CreditRole](c, row.Role),
			Attribution: enumOf[domain.Attribution](c, row.Attribution),
			Certainty:   enumOf[domain.Certainty](c, row.Certainty),
			Part:        nullEnumOf[domain.PiecePart](c, row.Part.PieceCreditsPart, row.Part.Valid),
			Note:        stringPtr(row.Note),
		}
		if row.PersonSlug.Valid {
			person := c.personSummary(row.PersonSlug.String, row.PersonName.String, row.PersonKind.PersonsKind,
				row.PersonIsStub.Bool)
			credit.Person = &person
		}
		credits = append(credits, credit)
	}

	return credits
}

// pieceRelations returns the outgoing relations, then the incoming ones. The two queries' rows have the same
// columns.
func (c *catalogueReader) pieceRelations(
	kinds map[string][]domain.PieceKind,
	to []queries.ListPublicPieceRelationsToRow,
	from []queries.ListPublicPieceRelationsFromRow,
) []domain.PieceRelation {
	relations := make([]domain.PieceRelation, 0, len(to)+len(from))
	add := func(row queries.ListPublicPieceRelationsToRow, direction domain.RelationDirection) {
		relations = append(relations, domain.PieceRelation{
			Type:      enumOf[domain.PieceRelationType](c, row.Type),
			Direction: direction,
			Piece:     c.pieceSummary(kinds, row.Slug, row.Title, row.Kind, row.ConservationStatus, row.IsStub),
		})
	}
	for _, row := range to {
		add(row, domain.RelationDirectionOutgoing)
	}
	for _, row := range from {
		add(queries.ListPublicPieceRelationsToRow(row), domain.RelationDirectionIncoming)
	}

	return relations
}

// links groups attachment rows, ordered by position, into one Link per link in the order of its first
// attachment, with its roles in attachment order. It also returns the links' IDs, in the same order.
func (c *catalogueReader) links(rows []queries.ListPublicPieceLinksRow) ([]domain.Link, []uint64) {
	var (
		links []domain.Link
		ids   []uint64
		index = make(map[uint64]int)
	)
	for _, row := range rows {
		i, seen := index[row.ID]
		if !seen {
			i = len(links)
			index[row.ID] = i
			ids = append(ids, row.ID)
			links = append(links, c.link(row))
		}
		links[i].Roles = append(links[i].Roles, enumOf[domain.LinkRole](c, row.Role))
	}

	return links, ids
}

func (c *catalogueReader) link(row queries.ListPublicPieceLinksRow) domain.Link {
	link := domain.Link{
		URL:           row.Url,
		Title:         stringPtr(row.Title),
		Description:   stringPtr(row.Description),
		Platform:      stringPtr(row.Platform),
		PlaceType:     nullEnumOf[domain.LinkPlaceType](c, row.PlaceType.LinksPlaceType, row.PlaceType.Valid),
		Locator:       stringPtr(row.Locator),
		Liveness:      enumOf[domain.Liveness](c, row.Liveness),
		LastCheckedAt: timePtr(row.LastCheckedAt),
		ArchivedURL:   stringPtr(row.ArchivedUrl),
	}
	if row.CollectionID.Valid {
		link.Collection = &domain.CollectionRef{ID: row.CollectionID.Int64, Name: row.CollectionName.String}
	}

	return link
}

// pieceLinks returns the visible links of the piece with ID key, each with the piece's performances it records.
func (c *catalogueReader) pieceLinks(ctx context.Context, key sql.NullInt64) []domain.PieceLink {
	links, linkIDs := c.links(fetch(ctx, c, "links", c.q.ListPublicPieceLinks, key))
	rows := fetch(ctx, c, "performances", c.q.ListPublicPiecePerformances, key)

	performanceIDs := make([]uint64, 0, len(rows))
	for _, row := range rows {
		performanceIDs = append(performanceIDs, row.ID)
	}
	performers := c.performers(ctx, performanceIDs)

	byLink := make(map[uint64][]domain.PiecePerformance)
	for _, row := range rows {
		byLink[row.LinkID] = append(byLink[row.LinkID], domain.PiecePerformance{
			Year:                int16Ptr(row.Year),
			Uploader:            stringPtr(row.Uploader),
			DescriptionVerbatim: row.DescriptionVerbatim,
			Event:               c.eventSummary(row.EventSlug, row.EventName, row.EventKind),
			Performers:          performers[row.ID],
		})
	}

	pieceLinks := make([]domain.PieceLink, 0, len(links))
	for i, link := range links {
		pieceLinks = append(pieceLinks, domain.PieceLink{Link: link, Performances: byLink[linkIDs[i]]})
	}

	return pieceLinks
}

// performers returns the public performers of each of the performances, in position order, by performance ID.
func (c *catalogueReader) performers(ctx context.Context, performanceIDs []uint64) map[uint64][]domain.PersonSummary {
	performers := make(map[uint64][]domain.PersonSummary)
	if len(performanceIDs) == 0 {
		return performers
	}
	for _, row := range fetch(ctx, c, "performers", c.q.ListPublicPerformers, performanceIDs) {
		performers[row.PerformanceID] = append(performers[row.PerformanceID],
			c.personSummary(row.Slug, row.Name, row.Kind, row.IsStub))
	}

	return performers
}

