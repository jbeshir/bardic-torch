func (c *catalogueReader) person(ctx context.Context, slug string) domain.Person {
	row, err := c.q.GetPublicPerson(ctx, slug)
	if errors.Is(err, sql.ErrNoRows) {
		c.fail(datasources.ErrNotFound)
		return domain.Person{}
	}
	if err != nil {
		c.fail(fmt.Errorf("fetching person: %w", err))
		return domain.Person{}
	}

	status := enumOf[domain.PersonStatus](c, row.Status)
	person := domain.Person{
		PersonSummary: domain.PersonSummary{
			Slug:   row.Slug,
			Name:   row.Name,
			Kind:   enumOf[domain.PersonKind](c, row.Kind),
			IsStub: domain.PersonIsStub(row.IsStub, status),
		},
		Status:          status,
		StatusDate:      timePtr(row.StatusDate),
		StatusSourceURL: stringPtr(row.StatusSourceUrl),
	}
	if status != domain.PersonStatusPrefersNoPage {
		person.Profile = c.personProfile(ctx, row)
	}

	return person
}

func (c *catalogueReader) personProfile(ctx context.Context, row queries.GetPublicPersonRow) *domain.PersonProfile {
	key := c.nullID(row.ID)
	works := fetch(ctx, c, "works", c.q.ListPublicPersonWorks,
		queries.ListPublicPersonWorksParams{PersonID: key, Limit: domain.MaxNestedListItems})
	performances := fetch(ctx, c, "performances", c.q.ListPublicPersonPerformances,
		queries.ListPublicPersonPerformancesParams{
			PerformerID: row.ID, AttachedPersonID: key, Limit: domain.MaxNestedListItems,
		})

	var slugs []string
	for _, work := range works {
		slugs = append(slugs, work.Slug)
	}
	for _, performance := range performances {
		if performance.PieceSlug.Valid {
			slugs = append(slugs, performance.PieceSlug.String)
		}
	}
	kinds := c.secondaryKinds(ctx, slugs)

	links, _ := c.links(personLinkRows(fetch(ctx, c, "links", c.q.ListPublicPersonLinks, key)))

	return &domain.PersonProfile{
		Pronouns:         stringPtr(row.Pronouns),
		NotesMD:          stringPtr(row.NotesMd),
		LicensingStatus:  enumOf[domain.LicensingStatus](c, row.LicensingStatus),
		LicensingNotesMD: stringPtr(row.LicensingNotesMd),
		Aliases:          c.personAliases(fetch(ctx, c, "aliases", c.q.ListPublicPersonAliases, row.ID)),
		Roles:            c.personRoles(fetch(ctx, c, "roles", c.q.ListPersonRoles, row.ID)),
		Affiliations:     c.affiliations(fetch(ctx, c, "affiliations", c.q.ListPublicPersonAffiliations, row.ID)),
		Relations: c.personRelations(
			fetch(ctx, c, "outgoing relations", c.q.ListPublicPersonRelationsTo, row.ID),
			fetch(ctx, c, "incoming relations", c.q.ListPublicPersonRelationsFrom, row.ID)),
		Links:        links,
		Works:        c.personWorks(kinds, works),
		WorksTotal:   fetch(ctx, c, "work count", c.q.CountPublicPersonWorks, key),
		Performances: c.personPerformances(kinds, performances),
		PerformancesTotal: fetch(ctx, c, "performance count", c.q.CountPublicPersonPerformances,
			queries.CountPublicPersonPerformancesParams{PerformerID: row.ID, AttachedPersonID: key}),
	}
}

// personLinkRows converts a person's link rows to the piece link rows, which have the same columns, so that
// links groups both.
func personLinkRows(rows []queries.ListPublicPersonLinksRow) []queries.ListPublicPieceLinksRow {
	converted := make([]queries.ListPublicPieceLinksRow, 0, len(rows))
	for _, row := range rows {
		converted = append(converted, queries.ListPublicPieceLinksRow(row))
	}

	return converted
}

